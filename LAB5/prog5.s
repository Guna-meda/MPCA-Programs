.DATA
A:.WORD 5,4,3,2,1

.TEXT
LDR R13,=A
LDMFD R13!,{R1-R5}
MOV R0,#0

LOOP_I:
	CMP R0,#4	;N-1
	BNE LOOP_J	;I


SWI 0X011

LOOP_J:
	RSB R8,R0,#4	;N-I-1
	MOV R7,#0	;J
	LDR R6,=A
	

LOOP:
	LDR R10,[R6,#4]
	LDR R9,[R6],#4
	CMP R9,R10
	BLGT SWAP
	ADD R7,R7,#1
	CMP R7,R8
	BNE LOOP

ADD R0,R0,#1
B LOOP_I


SWAP:
	MOV R11,R9
	MOV R9,R10
	MOV R10,R11
	STMED R6,{R9,R10}
	MOV PC,LR